using System.Reactive;

namespace Tests.System.Reactive.Shared;

public static partial class Seq
{
    /// <summary>
    /// Describes <c>Seq.FromEvent(conversion, addHandler, removeHandler)</c> with a conversion from
    /// the handler to the event's delegate type.
    /// </summary>
    /// <typeparam name="TDelegate">The delegate type of the event to convert.</typeparam>
    /// <typeparam name="TEventArgs">The type of the event data generated by the event.</typeparam>
    /// <param name="conversion">
    /// A function used to convert the given event handler to a delegate compatible with the
    /// underlying .NET event. The resulting delegate is used in calls to the addHandler and
    /// removeHandler action parameters.
    /// </param>
    /// <param name="addHandler">
    /// Action that attaches the given event handler to the underlying .NET event.
    /// </param>
    /// <param name="removeHandler">
    /// Action that detaches the given event handler from the underlying .NET event.
    /// </param>
    /// <remarks>
    /// Builds a <see cref="FromEventConversionSeq{TDelegate, TEventArgs}"/>, which each target materializes through
    /// <see cref="ISeqVisitor.FromEventConversion{TDelegate, TEventArgs}(FromEventConversionSeq{TDelegate, TEventArgs})"/>.
    /// </remarks>
    public static Seq<TEventArgs> FromEvent<TDelegate, TEventArgs>(
        Func<Action<TEventArgs>, TDelegate> conversion,
        Action<TDelegate> addHandler,
        Action<TDelegate> removeHandler) =>
        new FromEventConversionSeq<TDelegate, TEventArgs>(conversion, addHandler, removeHandler,
                null);

    /// <summary>
