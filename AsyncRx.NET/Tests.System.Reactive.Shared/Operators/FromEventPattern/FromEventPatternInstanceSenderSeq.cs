using System.Reactive;

namespace Tests.System.Reactive.Shared;

/// <summary>
/// Describes <c>Seq.FromEventPattern(target, eventName[, scheduler])</c> over an instance event
/// found by name, with typed sender and event arguments.
/// </summary>
/// <typeparam name="TSender">The type of the sender that raises the event.</typeparam>
/// <typeparam name="TEventArgs">The type of the event data generated by the event.</typeparam>
/// <remarks>
/// Built by the <c>Seq.FromEventPattern</c> overloads in <c>Seq.FromEventPattern.cs</c>;
/// materialized by each
/// target through <see cref="ISeqVisitor.FromEventPatternInstanceSender{TSender, TEventArgs}(FromEventPatternInstanceSenderSeq{TSender, TEventArgs})"/>.
/// </remarks>
public sealed class FromEventPatternInstanceSenderSeq<TSender, TEventArgs>(object target,
        string eventName, SchedulerRef? scheduler)
    : Seq<EventPattern<TSender, TEventArgs>>
{
    /// <summary>Object instance that exposes the event to convert.</summary>
    public object Target => target;

    /// <summary>Name of the event to convert.</summary>
    public string EventName => eventName;

    /// <summary>
    /// Scheduler to run the event conversion on, or null for the target's default.
    /// </summary>
    public SchedulerRef? Scheduler => scheduler;

    /// <inheritdoc/>
    protected override Realized<Seq<EventPattern<TSender, TEventArgs>>> AcceptCore(
            ISeqVisitor visitor) =>
        visitor.FromEventPatternInstanceSender(this);

    /// <inheritdoc/>
    public override string ToString() =>
        scheduler is null
            ? "Seq.FromEventPattern(target, eventName)"
            : $"Seq.FromEventPattern(target, eventName, {scheduler})";
}
