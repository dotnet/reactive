using System.Reactive;

namespace Tests.System.Reactive.Shared;

/// <summary>
/// Describes <c>Seq.FromEventPattern(conversion, addHandler, removeHandler[, scheduler])</c> with a
/// conversion from the handler to the event's delegate type.
/// </summary>
/// <typeparam name="TDelegate">The delegate type of the event to convert.</typeparam>
/// <typeparam name="TEventArgs">The type of the event data generated by the event.</typeparam>
/// <remarks>
/// Built by the <c>Seq.FromEventPattern</c> overloads in <c>Seq.FromEventPattern.cs</c>;
/// materialized by each
/// target through <see cref="ISeqVisitor.FromEventPatternConversion{TDelegate, TEventArgs}(FromEventPatternConversionSeq{TDelegate, TEventArgs})"/>.
/// </remarks>
public sealed class FromEventPatternConversionSeq<TDelegate, TEventArgs>(Func<EventHandler<
        TEventArgs>, TDelegate> conversion, Action<TDelegate> addHandler, Action<
        TDelegate> removeHandler, SchedulerRef? scheduler)
    : Seq<EventPattern<TEventArgs>>
{
    /// <summary>
    /// A function used to convert the given event handler to a delegate compatible with the
    /// underlying .NET event. The resulting delegate is used in calls to the addHandler and
    /// removeHandler action parameters.
    /// </summary>
    public Func<EventHandler<TEventArgs>, TDelegate> Conversion => conversion;

    /// <summary>
    /// Action that attaches the given event handler to the underlying .NET event.
    /// </summary>
    public Action<TDelegate> AddHandler => addHandler;

    /// <summary>
    /// Action that detaches the given event handler from the underlying .NET event.
    /// </summary>
    public Action<TDelegate> RemoveHandler => removeHandler;

    /// <summary>
    /// Scheduler to run the event conversion on, or null for the target's default.
    /// </summary>
    public SchedulerRef? Scheduler => scheduler;

    /// <inheritdoc/>
    protected override Realized<Seq<EventPattern<TEventArgs>>> AcceptCore(ISeqVisitor visitor) =>
        visitor.FromEventPatternConversion(this);

    /// <inheritdoc/>
    public override string ToString() =>
        scheduler is null
            ? "Seq.FromEventPattern(conversion, addHandler, removeHandler)"
            : $"Seq.FromEventPattern(conversion, addHandler, removeHandler, {scheduler})";
}
