using System.Reactive;

namespace Tests.System.Reactive.Shared;

/// <summary>
/// Describes <c>Seq.FromEventPattern(addHandler, removeHandler[, scheduler])</c> over an event of
/// any delegate type, keeping the sender's type.
/// </summary>
/// <typeparam name="TDelegate">The delegate type of the event to convert.</typeparam>
/// <typeparam name="TSender">The type of the sender that raises the event.</typeparam>
/// <typeparam name="TEventArgs">The type of the event data generated by the event.</typeparam>
/// <remarks>
/// Built by the <c>Seq.FromEventPattern</c> overloads in <c>Seq.FromEventPattern.cs</c>;
/// materialized by each
/// target through <see cref="ISeqVisitor.FromEventPatternSender{TDelegate, TSender, TEventArgs}(FromEventPatternSenderSeq{TDelegate, TSender, TEventArgs})"/>.
/// </remarks>
public sealed class FromEventPatternSenderSeq<TDelegate, TSender, TEventArgs>(Action<
        TDelegate> addHandler, Action<TDelegate> removeHandler, SchedulerRef? scheduler)
    : Seq<EventPattern<TSender, TEventArgs>>
{
    /// <summary>
    /// Action that attaches the given event handler to the underlying .NET event.
    /// </summary>
    public Action<TDelegate> AddHandler => addHandler;

    /// <summary>
    /// Action that detaches the given event handler from the underlying .NET event.
    /// </summary>
    public Action<TDelegate> RemoveHandler => removeHandler;

    /// <summary>
    /// Scheduler to run the event conversion on, or null for the target's default.
    /// </summary>
    public SchedulerRef? Scheduler => scheduler;

    /// <inheritdoc/>
    protected override Realized<Seq<EventPattern<TSender, TEventArgs>>> AcceptCore(
            ISeqVisitor visitor) =>
        visitor.FromEventPatternSender(this);

    /// <inheritdoc/>
    public override string ToString() =>
        scheduler is null
            ? "Seq.FromEventPattern(addHandler, removeHandler)"
            : $"Seq.FromEventPattern(addHandler, removeHandler, {scheduler})";
}
