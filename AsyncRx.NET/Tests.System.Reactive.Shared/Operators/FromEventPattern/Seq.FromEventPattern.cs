    /// </remarks>
    public static Seq<EventPattern<TEventArgs>> FromEventPattern<TDelegate, TEventArgs>(
        Func<EventHandler<TEventArgs>, TDelegate> conversion,
        Action<TDelegate> addHandler,
        Action<TDelegate> removeHandler) =>
        new FromEventPatternConversionSeq<TDelegate, TEventArgs>(conversion, addHandler,
                removeHandler, null);

