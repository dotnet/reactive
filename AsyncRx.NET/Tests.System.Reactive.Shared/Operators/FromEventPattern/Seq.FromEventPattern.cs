    /// <summary>
    /// Describes <c>Seq.FromEventPattern(addHandler, removeHandler)</c> over an <c>EventHandler</c>
    /// event.
    /// </summary>
    /// <param name="addHandler">
    /// Action that attaches the given event handler to the underlying .NET event.
    /// </param>
    /// <param name="removeHandler">
    /// Action that detaches the given event handler from the underlying .NET event.
    /// </param>
    /// <remarks>
    /// Builds a <see cref="FromEventPatternHandlerSeq"/>, which each target materializes through
    /// <see cref="ISeqVisitor.FromEventPatternHandler(FromEventPatternHandlerSeq)"/>.
    /// </remarks>
    public static Seq<EventPattern<object>> FromEventPattern(
        Action<EventHandler> addHandler,
        Action<EventHandler> removeHandler) =>
        new FromEventPatternHandlerSeq(addHandler, removeHandler, null);

